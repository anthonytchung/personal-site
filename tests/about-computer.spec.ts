import { test, expect } from "@playwright/test";

const utility = (page: import("@playwright/test").Page) => page.getByRole("dialog", { name: "About This Computer", exact: true });
async function openFromStart(page: import("@playwright/test").Page) {
  await page.getByRole("button", { name: "Start", exact: true }).click();
  await page.getByRole("navigation", { name: "Start menu" }).getByRole("button", { name: "About This Computer", exact: true }).click();
  await expect(utility(page)).toBeFocused();
}

test("utility is independent, persists across navigation, focuses without duplicating, and closes to its opener", async ({ page }, testInfo) => {
  await page.goto("/about");
  await expect(page.locator("time")).toHaveAttribute("datetime", /.+/);
  const primary = page.locator("#primary-window");
  const geometry = await primary.boundingBox();
  const launch = page.getByRole("button", { name: "Open About This Computer" });
  await launch.click();
  await expect(utility(page)).toBeFocused();
  await expect(page).toHaveURL("/about");
  expect(await primary.boundingBox()).toEqual(geometry);
  await expect(primary).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("two-windows.png") });
  await utility(page).getByRole("button", { name: "Minimize", exact: true }).click();
  await expect(utility(page)).toBeHidden();
  await page.getByRole("button", { name: "Restore About This Computer", exact: true }).click();
  await expect(utility(page)).toBeFocused();
  await openFromStart(page);
  await expect(utility(page)).toHaveCount(1);
  await primary.getByRole("link", { name: "Projects", exact: true }).click();
  await expect(page).toHaveURL("/projects");
  await expect(utility(page)).toBeVisible();
  await expect(primary).toHaveClass(/active/);
  await page.getByRole("button", { name: "Restore About This Computer", exact: true }).click();
  await expect(utility(page)).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(utility(page)).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Start", exact: true })).toBeFocused();
  await openFromStart(page);
  await expect(utility(page).getByRole("navigation")).toHaveCount(0);
  await expect(utility(page).getByRole("link")).toHaveCount(0);
  await page.getByRole("button", { name: "Restore Projects", exact: true }).click();
  await primary.getByRole("link", { name: "About", exact: true }).click();
  await expect(page).toHaveURL("/about");
  await page.reload();
  await expect(utility(page)).toHaveCount(0);
  await expect(page.getByRole("heading", { name: "Hi, I’m Anthony.", exact: true })).toBeVisible();
});

test("shared movement, Escape cancellation, focus stacking and Show Desktop preserve both geometries", async ({ page }) => {
  await page.goto("/projects");
  await expect(page.locator("time")).toHaveAttribute("datetime", /.+/);
  await openFromStart(page);
  const title = utility(page).getByRole("group", { name: "About This Computer window title bar" });
  const original = (await utility(page).boundingBox())!;
  await title.focus();
  await page.keyboard.press("ArrowLeft");
  expect((await utility(page).boundingBox())!.x).toBe(original.x - 10);
  const moved = await utility(page).boundingBox();
  await utility(page).getByRole("button", { name: "Maximize", exact: true }).click();
  const maximized = (await utility(page).boundingBox())!;
  expect(maximized.x).toBe(8);
  expect(maximized.width).toBe(1350);
  await utility(page).getByRole("button", { name: "Restore", exact: true }).click();
  expect(await utility(page).boundingBox()).toEqual(moved);
  await expect(page).toHaveURL("/projects");
  const handle = (await title.boundingBox())!;
  await page.mouse.move(handle.x + 50, handle.y + 15);
  await page.mouse.down();
  await page.mouse.move(handle.x + 85, handle.y + 40);
  await page.keyboard.press("Escape");
  await page.mouse.up();
  await expect(utility(page)).toBeVisible();
  expect(await utility(page).boundingBox()).toEqual(moved);
  const primary = page.locator("#primary-window");
  const primaryBox = await primary.boundingBox();
  const desktop = page.getByRole("button", { name: "Show desktop", exact: true });
  await desktop.hover();
  await expect(utility(page).locator(":scope > div").last()).toHaveCSS("opacity", "0");
  await desktop.click();
  await expect(primary).toBeHidden();
  await expect(utility(page)).toBeHidden();
  await desktop.click();
  await page.mouse.move(1200, 100);
  await expect(primary).toBeVisible();
  await expect(utility(page)).toBeVisible();
  expect(await utility(page).boundingBox()).toEqual(moved);
  expect(await primary.boundingBox()).toEqual(primaryBox);
  await utility(page).getByRole("button", { name: "Minimize", exact: true }).click();
  await desktop.click();
  await desktop.click();
  await expect(utility(page)).toBeHidden();
  await expect(primary).toBeVisible();
});

