test("opening the utility preserves a minimized primary and mobile history reveals route content", async ({ page }) => {
  await page.goto("/about");
  await expect(page.locator("time")).toHaveAttribute("datetime", /.+/);
  await page.getByRole("button", { name: "Minimize About", exact: true }).click();
  await openFromStart(page);
  await expect(page.locator("#primary-window")).toBeHidden();
  await utility(page).getByRole("button", { name: "Close", exact: true }).click();
  await expect(page.locator("#primary-window")).toBeHidden();
  await page.getByRole("button", { name: "Restore About", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("navigation", { name: "Desktop shortcuts" }).getByRole("link", { name: "Projects", exact: true }).click();
  await openFromStart(page);
  await page.goBack();
  await expect(page).toHaveURL("/about");
  await expect(page.locator("#primary-window")).toBeVisible();
  await expect(utility(page)).toBeHidden();
  await page.goForward();
  await expect(page).toHaveURL("/projects");
  await expect(page.getByRole("heading", { name: "Projects", exact: true })).toBeVisible();
});

test("maximized biography uses balanced columns and a narrow utility keeps its content reachable", async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1920, height: 1080 });
  await page.goto("/about");
  await expect(page.locator("time")).toHaveAttribute("datetime", /.+/);
  const primary = page.locator("#primary-window");
  await primary.getByRole("button", { name: "Maximize", exact: true }).click();
  const background = page.getByRole("region", { name: "People & technology", exact: true });
  const interests = page.getByRole("region", { name: "Away from the keyboard", exact: true });
  const left = (await background.boundingBox())!;
  const right = (await interests.boundingBox())!;
  expect(left.y).toBe(right.y);
  expect(right.x).toBeGreaterThan(left.x + left.width);
  await page.screenshot({ path: testInfo.outputPath("about-maximized.png") });
  const original = await primary.boundingBox();
  await page.getByRole("button", { name: "Open About This Computer" }).click();
  expect(await primary.boundingBox()).toEqual(original);
  const resize = utility(page).getByRole("button", { name: "Resize window", exact: true });
  await resize.focus();
  await page.keyboard.press("ArrowLeft");
  for (let step = 0; step < 23; step++) await page.keyboard.press("ArrowLeft");
  expect((await utility(page).boundingBox())!.width).toBe(520);
  expect(await utility(page).evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  const origin = utility(page).getByText("My interest in technology began", { exact: false });
  await origin.scrollIntoViewIfNeeded();
  await expect(origin).toBeInViewport();
  await page.screenshot({ path: testInfo.outputPath("utility-narrow.png") });
});
