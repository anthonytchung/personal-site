import { test, expect, type Page } from "@playwright/test";

const route = "/travellogs/publishing-verification-fixture";
const viewer = (page: Page) => page.locator("#photo-viewer-window");
const photoImage = (page: Page) => viewer(page).locator("img");
const galleryLink = (page: Page) => page.getByRole("group", { name: "Test gallery", exact: true }).getByRole("link").first();
async function article(page: Page) {
  await page.goto(route);
  await expect(page.getByRole("button", { name: "Date and time", exact: true }).locator("time")).toHaveAttribute("datetime", /.+/);
  await galleryLink(page).scrollIntoViewIfNeeded();
}
async function open(page: Page) {
  await galleryLink(page).click();
  await expect(viewer(page).locator("[data-photo-content]")).toBeFocused();
}

test("synthetic photograph assets and articles are excluded from the real build", async ({ request, page }) => {
  test.skip(process.env.WRITING_FIXTURES === "1", "This assertion checks the real build after fixture cleanup.");
  expect((await request.get("/images/__photo-viewer-fixtures/landscape.svg")).status()).toBe(404);
  expect((await request.get(route)).status()).toBe(404);
  await page.goto("/travellogs");
  await expect(page.getByRole("link", { name: "Publishing verification fixture", exact: true })).toHaveCount(0);
});

test.describe("Photo Viewer with test-only MDX photographs", () => {
  test.skip(process.env.WRITING_FIXTURES !== "1", "Run bun run test:writing to build the temporary synthetic galleries.");

  test("MDX gallery opens without navigation or lost scroll; fit, actual size, arrows and captions work", async ({ page }, info) => {
    await article(page);
    const main = page.getByRole("main");
    const scroll = await main.evaluate(element => element.scrollTop);
    const primaryBox = await page.locator("#primary-window").boundingBox();
    await page.screenshot({ path: info.outputPath("before-gallery.png") });
    await open(page);
    await expect(page).toHaveURL(route);
    expect(await main.evaluate(element => element.scrollTop)).toBe(scroll);
    expect(await page.locator("#primary-window").boundingBox()).toEqual(primaryBox);
    await expect(photoImage(page)).toHaveAttribute("alt", "Blue and gold landscape test chart");
    await expect(viewer(page)).toContainText("Test location · 2026-11-01 · Test camera");
    const imageBox = (await photoImage(page).boundingBox())!;
    const stage = viewer(page).getByRole("group", { name: "Photograph", exact: true });
    const stageBox = (await stage.boundingBox())!;
    expect(imageBox.width).toBeLessThanOrEqual(stageBox.width);
    expect(imageBox.height).toBeLessThanOrEqual(stageBox.height);
    await page.screenshot({ path: info.outputPath("viewer-desktop.png") });
    await viewer(page).getByRole("button", { name: "Actual size", exact: true }).click();
    expect((await photoImage(page).boundingBox())!.width).toBe(1600);
    expect(await stage.evaluate(element => element.scrollWidth > element.clientWidth)).toBe(true);
    await viewer(page).getByRole("button", { name: "Zoom to fit", exact: true }).click();
    await stage.focus();
    await page.keyboard.press("ArrowRight");
    await expect(photoImage(page)).toHaveAttribute("alt", "Brown and gray portrait test chart");
    await expect(viewer(page).getByRole("button", { name: "Zoom to fit", exact: true })).toHaveAttribute("aria-pressed", "true");
    await page.keyboard.press("ArrowLeft");
    await expect(photoImage(page)).toHaveAttribute("alt", "Blue and gold landscape test chart");
    await page.keyboard.press("Escape");
    await expect(viewer(page)).toHaveCount(0);
    await expect(galleryLink(page)).toBeFocused();
    expect(await main.evaluate(element => element.scrollTop)).toBe(scroll);
    await expect(page).toHaveURL(route);
  });

  test("shared frame preserves movement, resize, minimize, stacking, Peek, Show Desktop and route state", async ({ page }, info) => {
    await article(page); await open(page);
    const title = viewer(page).getByRole("group", { name: /window title bar$/ });
    const original = (await viewer(page).boundingBox())!;
    await title.focus(); await page.keyboard.press("ArrowLeft");
    expect((await viewer(page).boundingBox())!.x).toBe(original.x - 10);
    const moved = await viewer(page).boundingBox();
    const handle = (await title.boundingBox())!;
    await page.mouse.move(handle.x + 50, handle.y + 14); await page.mouse.down();
    await page.mouse.move(handle.x + 100, handle.y + 40); await page.keyboard.press("Escape"); await page.mouse.up();
    expect(await viewer(page).boundingBox()).toEqual(moved);
    const resize = viewer(page).getByRole("button", { name: "Resize window", exact: true });
    await resize.focus(); for (let i = 0; i < 36; i++) await page.keyboard.press("ArrowLeft");
    expect((await viewer(page).boundingBox())!.width).toBe(520);
    await page.screenshot({ path: info.outputPath("viewer-narrow.png") });
    const narrowed = await viewer(page).boundingBox();
    await viewer(page).getByRole("button", { name: "Maximize", exact: true }).click();
    await page.screenshot({ path: info.outputPath("viewer-maximized.png") });
    await viewer(page).getByRole("button", { name: "Restore", exact: true }).click();
    expect(await viewer(page).boundingBox()).toEqual(narrowed);
    await viewer(page).getByRole("button", { name: "Next photograph", exact: true }).click();
    await viewer(page).getByRole("button", { name: "Minimize", exact: true }).click();
    await expect(viewer(page)).toBeHidden();
    await page.locator("#photo-task").hover();
    await expect(page.locator("#photo-preview")).toBeVisible();
    await expect(page.locator("#photo-preview image")).toHaveAttribute("href", "/images/__photo-viewer-fixtures/portrait.svg");
    await page.screenshot({ path: info.outputPath("photo-thumbnail.png") });
    await page.locator("#photo-preview").click();
    await expect(viewer(page).locator("[data-photo-content]")).toBeFocused();
    await expect(photoImage(page)).toHaveAttribute("alt", "Brown and gray portrait test chart");
    expect(await viewer(page).boundingBox()).toEqual(narrowed);
    await page.getByRole("button", { name: "Start", exact: true }).click();
    await page.getByRole("navigation", { name: "Start menu" }).getByRole("button", { name: "About This Computer", exact: true }).click();
    await expect(page.locator("#about-computer-window")).toBeFocused();
    await expect(page.locator("#about-computer-window")).toHaveClass(/active/);
    await page.locator("#utility-task").click();
    await expect(viewer(page)).toHaveClass(/active/);
    await page.locator("#utility-task").click();
    await expect(page.locator("#about-computer-window")).toHaveClass(/active/);
    await page.locator("#photo-task").click();
    await expect(viewer(page)).toHaveClass(/active/);
    await expect(page.locator("#about-computer-window")).not.toHaveClass(/active/);
    const desktop = page.getByRole("button", { name: "Show desktop", exact: true });
    await desktop.hover();
    await expect(viewer(page).locator(":scope > div").last()).toHaveCSS("opacity", "0");
    await desktop.click();
    for (const id of ["primary-window", "about-computer-window", "photo-viewer-window"]) await expect(page.locator(`#${id}`)).toBeHidden();
    await desktop.click(); await page.mouse.move(1200, 100);
    await expect(viewer(page)).toBeVisible();
    expect(await viewer(page).boundingBox()).toEqual(narrowed);
    await page.locator("#primary-task").click();
    await page.getByRole("complementary", { name: "Explorer navigation" }).getByRole("link", { name: "Projects", exact: true }).click();
    await expect(page).toHaveURL("/projects");
    await page.locator("#photo-task").click();
    await expect(photoImage(page)).toHaveAttribute("alt", "Brown and gray portrait test chart");
    await viewer(page).getByRole("button", { name: "Close", exact: true }).click();
    await expect(page).toHaveURL("/projects");
    await page.goBack();
    await expect(page).toHaveURL(route);
    await expect(viewer(page)).toHaveCount(0);
    await page.locator("#utility-task").click();
    await page.locator("#about-computer-window").getByRole("button", { name: "Close", exact: true }).click();
    await galleryLink(page).scrollIntoViewIfNeeded();
    await open(page);
    await page.locator("#primary-task").click();
    await page.locator("#primary-window").getByRole("button", { name: "Close", exact: true }).click();
    await expect(page).toHaveURL("/");
    await expect(page.locator("#primary-window")).toHaveAttribute("aria-label", "Welcome to Anthony's Desktop");
    await page.locator("#primary-window").getByRole("button", { name: "Close", exact: true }).click();
    await expect(page.locator("#primary-window")).toBeHidden();
    await page.locator("#photo-task").click();
    await viewer(page).getByRole("button", { name: "Close", exact: true }).click();
    await expect(page.getByRole("button", { name: "Start", exact: true })).toBeFocused();
  });

  test("slideshow is opt-in, pauses when minimized, stops on Escape and respects reduced motion", async ({ page }) => {
    await page.clock.install();
    await article(page); await open(page);
    await page.clock.fastForward(6000);
    await expect(photoImage(page)).toHaveAttribute("alt", "Blue and gold landscape test chart");
    await viewer(page).getByRole("button", { name: "Start slideshow", exact: true }).click();
    await page.clock.fastForward(5100);
    await expect(photoImage(page)).toHaveAttribute("alt", "Brown and gray portrait test chart");
    await viewer(page).getByRole("button", { name: "Minimize", exact: true }).click();
    await page.clock.fastForward(10000);
    await page.locator("#photo-task").click();
    await page.clock.runFor(30);
    await expect(viewer(page).locator("[data-photo-content]")).toBeFocused();
    await expect(photoImage(page)).toHaveAttribute("alt", "Brown and gray portrait test chart");
    await page.keyboard.press("Escape");
    await expect(viewer(page)).toBeVisible();
    await expect(viewer(page).getByRole("button", { name: "Start slideshow", exact: true })).toBeVisible();
    await page.keyboard.press("Escape");
    await expect(viewer(page)).toHaveCount(0);
    await page.emulateMedia({ reducedMotion: "reduce" });
    await open(page);
    await expect(viewer(page).getByRole("button", { name: "Start slideshow", exact: true })).toBeDisabled();
    await viewer(page).getByRole("button", { name: "Next photograph", exact: true }).click();
    await expect(photoImage(page)).toHaveAttribute("alt", "Brown and gray portrait test chart");
  });

  test("mobile opens full screen, traps focus, supports touch-sized controls and restores article scroll", async ({ page }, info) => {
    await page.setViewportSize({ width: 390, height: 844 });
    await article(page);
    const scroll = await page.evaluate(() => scrollY);
    await page.screenshot({ path: info.outputPath("before-mobile-gallery.png") });
    await open(page);
    await expect(viewer(page)).toHaveAttribute("aria-modal", "true");
    const bounds = (await viewer(page).boundingBox())!;
    expect(bounds.x).toBe(0); expect(bounds.y).toBe(0); expect(bounds.width).toBe(390); expect(bounds.height).toBe(844);
    await expect(page.locator("body")).toHaveCSS("overflow", "hidden");
    await expect(page.locator("#primary-window").locator("..")).toHaveAttribute("inert", "");
    await page.keyboard.press("Tab");
    await expect(viewer(page).getByRole("button", { name: "Close", exact: true })).toBeFocused();
    await page.keyboard.press("Shift+Tab");
    await expect(viewer(page).getByRole("button", { name: "Next photograph", exact: true })).toBeFocused();
    for (const name of ["Previous photograph", "Next photograph", "Actual size", "Zoom to fit"]) expect((await viewer(page).getByRole("button", { name, exact: true }).boundingBox())!.height).toBeGreaterThanOrEqual(44);
    await viewer(page).getByRole("button", { name: "Next photograph", exact: true }).click();
    await expect(photoImage(page)).toHaveAttribute("alt", "Brown and gray portrait test chart");
    await page.screenshot({ path: info.outputPath("viewer-mobile.png") });
    await viewer(page).getByRole("button", { name: "Close", exact: true }).click();
    await expect(viewer(page)).toHaveCount(0);
    await expect(galleryLink(page)).toBeFocused();
    expect(await page.evaluate(() => scrollY)).toBe(scroll);
    await expect(page.locator("body")).not.toHaveCSS("overflow", "hidden");
    await expect(page).toHaveURL(route);
  });

  test("mobile history and viewport changes release modal state without losing the photo", async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto("/travellogs");
    await page.getByRole("link", { name: "Publishing verification fixture", exact: true }).click();
    await galleryLink(page).scrollIntoViewIfNeeded();
    await open(page);
    await page.setViewportSize({ width: 1366, height: 768 });
    await expect(viewer(page)).not.toHaveAttribute("aria-modal", "true");
    await expect(page.locator("body")).not.toHaveCSS("overflow", "hidden");
    await expect(page.locator("#primary-window").locator("..")).not.toHaveAttribute("inert", "");
    await expect(photoImage(page)).toHaveAttribute("alt", "Blue and gold landscape test chart");
    await page.setViewportSize({ width: 320, height: 568 });
    await expect(viewer(page)).toHaveAttribute("aria-modal", "true");
    expect((await viewer(page).boundingBox())!.width).toBe(320);
    await page.goBack();
    await expect(page).toHaveURL("/travellogs");
    await expect(viewer(page)).toBeHidden();
    await expect(page.locator("body")).not.toHaveCSS("overflow", "hidden");
    await expect(page.getByRole("main")).toBeVisible();
    await page.goForward();
    await expect(page).toHaveURL(route);
    await expect(viewer(page)).toBeHidden();
    await page.locator("#photo-task").click();
    await expect(viewer(page)).toBeVisible();
    await expect(photoImage(page)).toHaveAttribute("alt", "Blue and gold landscape test chart");
  });

  test("single images disable navigation; missing images fail gracefully and reload does not reopen the viewer", async ({ page }) => {
    await article(page);
    await page.getByRole("group", { name: "Single-image test gallery", exact: true }).getByRole("link").click();
    await expect(viewer(page).getByRole("button", { name: "Next photograph", exact: true })).toBeDisabled();
    await expect(viewer(page).getByRole("button", { name: "Previous photograph", exact: true })).toBeDisabled();
    await expect(viewer(page).getByRole("button", { name: "Start slideshow", exact: true })).toBeDisabled();
    await viewer(page).getByRole("button", { name: "Close", exact: true }).click();
    await page.getByRole("group", { name: "Missing-image test gallery", exact: true }).getByRole("link").click();
    await expect(viewer(page).getByText("This photograph couldn’t be loaded. You can try opening the original.", { exact: true })).toBeVisible();
    await expect(viewer(page).getByRole("link", { name: "Open original", exact: true })).toHaveAttribute("href", "/images/__photo-viewer-fixtures/missing.svg");
    await page.reload();
    await expect(viewer(page)).toHaveCount(0);
    await expect(page).toHaveURL(route);
  });
});
